#!/usr/bin/env bash
# Repository rule checks. Portable: bash 3.2, BSD grep, python3.
#  (a) no emoji in tracked files
#  (b) no AI-attribution phrases in tracked files or in commit messages
#      between origin/main and HEAD
#  (c) no obvious secrets
# Exempt from (b) and (c): CLAUDE.md and this script (they name the patterns).

cd "$(git rev-parse --show-toplevel)" || exit 2

fail=0
self="scripts/check-rules.sh"

# Pattern pieces are split so this file does not match itself.
attr_re='Co-Authored''-By: Claude|Co-Authored''-By|Generated with|Generated by Claude|Claude Code|claude\.ai/code/session|claude\.ai/code|noreply@anthropic'
secret_re='-----BEGIN [A-Z ]*PRIVATE KEY-----|ghp_[A-Za-z0-9]{20,}|AKIA[0-9A-Z]{16}|ASIA[0-9A-Z]{16}'

# Tracked files that still exist in the working tree.
files_tmp=$(mktemp)
trap 'rm -f "$files_tmp"' EXIT
git ls-files -z | python3 -c '
import os, sys
for p in sys.stdin.buffer.read().split(b"\0"):
    if p and os.path.isfile(p):
        sys.stdout.buffer.write(p + b"\0")
' > "$files_tmp"

# (a) emoji
python3 - "$files_tmp" <<'PY' || fail=1
import sys
# Ranges as code points so this file stays pure ASCII.
ranges = [(0x1F000, 0x1FAFF), (0x2300, 0x23FF), (0x2600, 0x27BF),
          (0x2B50, 0x2B55), (0xFE0F, 0xFE0F), (0x200D, 0x200D)]


def has_emoji(line):
    for ch in line:
        c = ord(ch)
        for lo, hi in ranges:
            if lo <= c <= hi:
                return True
    return False


paths = open(sys.argv[1], "rb").read().split(b"\0")
bad = 0
for raw in paths:
    if not raw:
        continue
    path = raw.decode()
    try:
        text = open(path, encoding="utf-8").read()
    except (UnicodeDecodeError, OSError):
        continue
    for n, line in enumerate(text.splitlines(), 1):
        if has_emoji(line):
            print("check-rules: emoji in %s:%d" % (path, n))
            bad = 1
sys.exit(bad)
PY

# (b), (c) on tracked files
while IFS= read -r -d '' f; do
  case "$f" in
    CLAUDE.md|"$self") continue ;;
  esac
  if grep -I -E -n -i -e "$attr_re" "$f" >/dev/null 2>&1; then
    echo "check-rules: AI-attribution phrase in $f"
    grep -I -E -n -i -e "$attr_re" "$f" | head -3
    fail=1
  fi
  if grep -I -E -n -e "$secret_re" "$f" >/dev/null 2>&1; then
    echo "check-rules: possible secret in $f"
    fail=1
  fi
done < "$files_tmp"

# (b) commit messages between origin/main and HEAD
if git rev-parse --verify -q origin/main >/dev/null; then
  if git log origin/main..HEAD --format=%B | grep -E -i -e "$attr_re" >/dev/null; then
    echo "check-rules: AI-attribution phrase in a commit message (origin/main..HEAD)"
    fail=1
  fi
else
  echo "check-rules: origin/main not found, skipping commit message check"
fi

if [ "$fail" -eq 0 ]; then
  echo "check-rules: ok"
fi
exit "$fail"

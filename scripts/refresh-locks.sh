#!/usr/bin/env bash
# Regenerates the conda lock files from environment.yml:
#   conda-linux-64.lock  conda-osx-arm64.lock
#
# Each file is an "explicit" conda spec: the URL and md5 of every package, in install order, with
# no solving left to do. micromamba solves environment.yml for the platform (from any host, using
# virtual-package overrides for the glibc / macOS version of the target), and this script writes
# the result. Needs only micromamba and python3.
#
# Usage: scripts/refresh-locks.sh [platform ...]     (default: linux-64 osx-arm64)
# Review the diff of the lock files before committing them (README.md, "Lock files").
set -euo pipefail

cd "$(dirname "$0")/.."
platforms=("$@")
if [ ${#platforms[@]} -eq 0 ]; then
  platforms=(linux-64 osx-arm64)
fi

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

for platform in "${platforms[@]}"; do
  case "$platform" in
    linux-64)  overrides=(CONDA_OVERRIDE_GLIBC=2.28) ;;   # conda-forge's baseline glibc
    osx-arm64) overrides=(CONDA_OVERRIDE_OSX=12.0) ;;
    *) echo "refresh-locks: unsupported platform $platform" >&2; exit 2 ;;
  esac
  echo "solving $platform ..." >&2
  env "${overrides[@]}" micromamba create --name vikshep-sim-lock --dry-run --json --yes \
      --platform "$platform" --file environment.yml > "$tmp/$platform.json"
  python3 - "$tmp/$platform.json" "$platform" "conda-$platform.lock" <<'PY'
import json
import sys

solved, platform, target = sys.argv[1:4]
doc = json.load(open(solved))
if not doc.get("success"):
    sys.exit("the solve for %s did not succeed" % platform)
links = doc["actions"]["LINK"]
lines = [
    "# Generated by scripts/refresh-locks.sh from environment.yml. Do not edit by hand.",
    "# platform: %s" % platform,
    "# Install with: micromamba create --name vikshep-sim --file %s" % target,
    "@EXPLICIT",
]
for package in links:
    lines.append("%s#%s" % (package["url"], package["md5"]))
open(target, "w").write("\n".join(lines) + "\n")
print("wrote %s: %d packages" % (target, len(links)), file=sys.stderr)
PY
done
